package ch.admin.bj.swiyu.core.business.modules.payment.domain.saferpay.model;

import com.fasterxml.jackson.annotation.JsonProperty;

/**
 * Header every Saferpay JSON API request has to carry.
 * See https://saferpay.github.io/jsonapi/#Payment_v1_PaymentPage_Initialize
 *
 * @param specVersion    version of the Saferpay JSON API this request is written against. Saferpay
 *                       interprets the request and shapes the response accordingly, so it must only be
 *                       raised together with the request/response classes.
 * @param customerId     our Saferpay customer id
 * @param requestId      id generated by us, unique per request (for tracing and support cases)
 * @param retryIndicator 0 for a first attempt; a higher number marks a resend of the same request with the
 *                       same requestId. We never resend, so it is always 0.
 */
public record SaferpayRequestHeader(
    @JsonProperty("SpecVersion") String specVersion,
    @JsonProperty("CustomerId") String customerId,
    @JsonProperty("RequestId") String requestId,
    @JsonProperty("RetryIndicator") int retryIndicator
) {}
